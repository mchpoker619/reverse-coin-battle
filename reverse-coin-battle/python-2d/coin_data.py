class Coin:
    __slots__ = ("id", "jp", "zh", "rarity", "main", "o", "x", "set")

    def __init__(self, cid, jp, rarity, main, o, x, setn):
        self.id, self.jp, self.rarity, self.main = cid, jp, rarity, main
        self.o, self.x, self.set = o, x, setn
        self.zh = CHAR_ZH.get(jp, "")

    @property
    def meta(self):
        return self.o != self.x

    @property
    def cost(self):
        """組隊預算（官方 p.7、p.10）：メタ幣算 M 值 =（正＋反）÷ 2，其他金幣就是 OX 值；合計 ≤ 15000。"""
        return (self.o + self.x) // 2

    def value(self, camp):
        """上場戰力：看自己陣營那一面。"""
        return self.o if camp == "O" else self.x


